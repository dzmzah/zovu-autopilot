// Реестр ТИПОВ рилсов.
//
// До этого тип был вшит в расписание: `rolki-auto.yml` каждый день звал
// `rolka-auto.mjs`, и лента получалась из одних и тех же роликов со стоком.
// Рисованные собирались отдельным воркфлоу, руками, и в очередь не попадали
// вообще — то есть второй тип у нас был, а в ленте его не было ни разу.
//
// Здесь тип — это строка в списке. Чтобы завести третий (например, рилс
// со скринкастом или с говорящим Kuba), надо добавить сюда одну запись и
// положить рядом сборщик, который кладёт готовый файл в `out/` под именем
// `auto-*.mp4`. Расписание, очередь, проверка замерами и выкладка уже
// умеют работать с чем угодно, что подходит под эту маску.
//
// `minuty` — грубая оценка сборки на сервере. Она нужна не для красоты:
// джоб живёт 45 минут, и если тип в него не влезает, лучше знать об этом
// до того, как он съест слот дня.

export const TYPY = [
  {
    klucz: 'stok',
    nazwa: 'живой сток + подписи',
    skrypt: 'rolka-auto.mjs',
    minuty: 12,
    // Сборщик сам крутит свои сценарии по кругу, тип ему аргументов не даёт.
    argi: () => [],
  },
  {
    klucz: 'grafika',
    nazwa: 'рисованный, без единого кадра стока',
    skrypt: 'rolka-grafika.mjs',
    minuty: 22,
    argi: () => [],
  },
];

// Как часто выходит каждый тип.
//
// Раньше типы чередовались строго через день. Это было честно, пока банки
// были одинаковой длины; после 31.08 стоковых сценариев стало двадцать два,
// а рисованных осталось семь — и при чередовании через день рисованный банк
// замыкал круг за две недели, то есть повторял ролик вдвое быстрее, чем
// стоковый. Частота типа должна идти от размера его банка, иначе память
// ротации не спасает: она честно скажет «повтор», но выбирать будет не из
// чего.
//
// Отсюда цикл из трёх слотов: два стоковых, один рисованный. При двадцати
// двух стоковых и десяти рисованных круг выходит в тридцать три и тридцать
// дней — оба длиннее месяца, то есть повтора зритель не увидит. Равные слоты
// вернуть НЕЛЬЗЯ, пока банки разной длины: рисованный замкнулся бы за
// двадцать дней и снова повторял бы ленту.
const SLOTY = ['stok', 'stok', 'grafika'];

// Следующий тип по очереди слотов. Слот сдвигается ДО сборки, а не после:
// если тип падает, завтра идёт следующий, а не тот же самый ещё раз. Лента
// важнее очерёдности — упавший тип вернётся через круг, когда его починят.
export function nastepnyTyp(stan, jawny = '') {
  if (jawny) {
    const t = TYPY.find((x) => x.klucz === jawny);
    if (!t) throw new Error(`нет типа «${jawny}», есть: ${TYPY.map((x) => x.klucz).join(', ')}`);
    return { typ: t, idx: TYPY.indexOf(t), slot: null, wybrany: 'руками' };
  }
  const slot = ((stan.slotRolki ?? -1) + 1) % SLOTY.length;
  const typ = TYPY.find((x) => x.klucz === SLOTY[slot]) || TYPY[0];
  return {
    typ,
    idx: TYPY.indexOf(typ),
    slot,
    wybrany: `слот ${slot + 1} из ${SLOTY.length}`,
  };
}
